/**
 * High-diversity handwritten glyph library with 3–5 genuinely distinct allographs
 * per frequent letter, directly modeled after the user's real Noteshelf 3 samples
 * ("Ja i moja rodzina", "Marek parkuje", "12.3/12.4").
 *
 * Notice in the user's real writing:
 * - Two 'a's in "mama" or "mała" are COMPLETELY different shapes
 * - Three 'e's in "interesuje" are all different (tight loop, tall open, flat c-like)
 * - 'm' ranges from a flat wide ~ wave ("Mam") to spiky narrow ("imam") to lopsided ("Jestem")
 * - 't' ranges from a tall hooked stroke ("Jestem") to a short '+' ("tam") to shifted crossbar ("programistą")
 * - 'o' ranges from tiny dot-like oval to tall open cup to hooked loop ("ogród")
 * - 'z' ranges from sharp angular to tiny flat to soft curved ("Bardzo")
 * - 'w' ranges from wide double-bowl to quick narrow 'v'-like ("w gry")
 *
 * Coordinate system (normalized to x-height = 1.0):
 *   x: 0 .. w (advance width)
 *   y:  0.0   = x-height top
 *       1.0   = baseline
 *      -0.95  = uppercase & ascender top
 *       1.78  = descender bottom
 */

export type Pt = readonly [number, number];
export type StrokeDef = readonly Pt[];

export interface GlyphDef {
  w: number;
  strokes: readonly StrokeDef[];
  /** Optional relative vertical bias (some letter variants sit slightly smaller/lower) */
  scaleBias?: number;
}

export type GlyphEntry = GlyphDef | readonly GlyphDef[];

function g(w: number, strokes: readonly StrokeDef[], scaleBias = 1.0): GlyphDef {
  return { w, strokes, scaleBias };
}

